const ORDERED = [...PLACES].sort((a, b) => b.name.length - a.name.length)

export type MentionedPlace = { name: string; lat: number; lon: number }

export function matchPlace(text: string): MentionedPlace | null {
  if (!text) return null
  for (const place of ORDERED) {
    const escaped = place.name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
    const pattern = new RegExp(`(?:^|[^A-Za-z0-9])${escaped}(?:[^A-Za-z0-9]|$)`, "i")
    if (!pattern.test(text)) continue
    if (place.name === "America" && /Latin\s+America|South\s+America|Central\s+America/i.test(text)) continue
    if (place.name === "Guinea" && /Papua New Guinea|Equatorial Guinea/i.test(text)) continue
    return place
  }
  return null
}
